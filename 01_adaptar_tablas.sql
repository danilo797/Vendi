-- VENDI · Etapa 1 · Adaptación a TUS tablas existentes
-- Ejecutar en Supabase > SQL Editor. NO borra ni reemplaza datos; es seguro repetirlo.
-- Tablas: clientes, productos, pedidos, pedido_items (ya existentes).

-- 1) Si alguna columna "id" no genera su propio número, se lo agregamos
--    continuando después del id más alto que ya exista.
do $$
declare
  t text;
  n bigint;
  es_ident text;
  def text;
begin
  foreach t in array array['clientes','productos','pedidos','pedido_items'] loop
    select is_identity, column_default into es_ident, def
      from information_schema.columns
     where table_schema = 'public' and table_name = t and column_name = 'id';
    if es_ident = 'NO' and def is null then
      execute format('select coalesce(max(id), 0) + 1 from public.%I', t) into n;
      execute format('alter table public.%I alter column id add generated by default as identity (start with %s)', t, n);
    end if;
  end loop;
end $$;

-- 2) Columnas nuevas (solo se agregan si faltan; lo existente no se toca)
alter table public.pedidos      add column if not exists notas  text;
alter table public.pedido_items add column if not exists nombre text;

create index if not exists pedidos_estado_idx on public.pedidos (estado);
create index if not exists pedidos_creado_idx on public.pedidos (creado_en desc);
create index if not exists items_pedido_idx   on public.pedido_items (pedido_id);

-- 3) Seguridad (RLS): solo usuarios con sesión iniciada leen o escriben.
alter table public.clientes     enable row level security;
alter table public.productos    enable row level security;
alter table public.pedidos      enable row level security;
alter table public.pedido_items enable row level security;

drop policy if exists "clientes_autenticados"      on public.clientes;
drop policy if exists "productos_autenticados"     on public.productos;
drop policy if exists "pedidos_autenticados"       on public.pedidos;
drop policy if exists "pedido_items_autenticados"  on public.pedido_items;

create policy "clientes_autenticados"     on public.clientes     for all to authenticated using (true) with check (true);
create policy "productos_autenticados"    on public.productos    for all to authenticated using (true) with check (true);
create policy "pedidos_autenticados"      on public.pedidos      for all to authenticated using (true) with check (true);
create policy "pedido_items_autenticados" on public.pedido_items for all to authenticated using (true) with check (true);

-- 4) Crea cliente (si no existe), pedido e ítems en una sola operación.
--    El total lo calcula el servidor. "canal" se guarda en pedidos.tipo.
create or replace function public.crear_pedido(
  p_cliente text, p_canal text, p_telefono text, p_notas text, p_items jsonb
) returns bigint
language plpgsql
as $$
declare
  v_cliente bigint;
  v_id bigint;
  v_tel text := nullif(trim(coalesce(p_telefono, '')), '');
  v_nombre text := nullif(trim(coalesce(p_cliente, '')), '');
begin
  if p_items is null or jsonb_array_length(p_items) = 0 then
    raise exception 'El pedido no tiene productos';
  end if;
  if v_nombre is null then
    raise exception 'Falta el nombre del cliente';
  end if;

  if v_tel is not null then
    select id into v_cliente from public.clientes where telefono = v_tel limit 1;
  else
    select id into v_cliente from public.clientes where lower(trim(nombre)) = lower(v_nombre) limit 1;
  end if;

  if v_cliente is null then
    insert into public.clientes (nombre, telefono) values (v_nombre, v_tel)
    returning id into v_cliente;
  end if;

  insert into public.pedidos (cliente_id, tipo, notas, estado, total)
  values (v_cliente, coalesce(p_canal, 'mostrador'), p_notas, 'pendiente', 0)
  returning id into v_id;

  insert into public.pedido_items (pedido_id, producto_id, nombre, cantidad, precio_unitario)
  select v_id, nullif(i->>'producto_id', '')::bigint, i->>'nombre', (i->>'cantidad')::int, (i->>'precio')::numeric
  from jsonb_array_elements(p_items) as i;

  update public.pedidos
     set total = (select coalesce(sum(cantidad * precio_unitario), 0)
                  from public.pedido_items where pedido_id = v_id)
   where id = v_id;

  return v_id;
end;
$$;

revoke execute on function public.crear_pedido(text, text, text, text, jsonb) from public, anon;
grant  execute on function public.crear_pedido(text, text, text, text, jsonb) to authenticated, service_role;

-- 5) Tiempo real: la pantalla se actualiza sola cuando cambie un pedido.
do $$
begin
  alter publication supabase_realtime add table public.pedidos;
exception when duplicate_object then null;
end $$;
