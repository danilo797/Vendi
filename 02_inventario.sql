-- 1) Tablas nuevas ----------------------------------------------------------

-- Una fila por producto que se lleva en stock.
create table if not exists public.inventario (
  id                 bigint generated by default as identity primary key,
  producto_id        bigint references public.productos (id) on delete set null,
  nombre             text not null,
  cantidad           numeric not null default 0,
  unidad             text not null default 'unidad',   -- unidad | docena | libra | kg | litro | caja
  minimo             numeric not null default 0,       -- debajo de esto se avisa
  costo_ultima_compra numeric,
  proveedor          text,
  actualizado_en     timestamptz not null default now()
);

-- Cada entrada o salida de mercadería queda registrada.
create table if not exists public.inventario_movimientos (
  id            bigint generated by default as identity primary key,
  inventario_id bigint not null references public.inventario (id) on delete cascade,
  tipo          text not null check (tipo in ('entrada', 'salida')),
  cantidad      numeric not null check (cantidad > 0),
  motivo        text,
  creado_en     timestamptz not null default now()
);

-- Órdenes de compra al proveedor.
create table if not exists public.compras (
  id           bigint generated by default as identity primary key,
  proveedor    text not null default 'Sin proveedor',
  estado       text not null default 'enviada' check (estado in ('borrador', 'enviada', 'recibida', 'cancelada')),
  total        numeric not null default 0,
  creado_en    timestamptz not null default now(),
  recibido_en  timestamptz
);

create table if not exists public.compra_items (
  id            bigint generated by default as identity primary key,
  compra_id     bigint not null references public.compras (id) on delete cascade,
  inventario_id bigint references public.inventario (id) on delete set null,
  nombre        text not null,
  cantidad      numeric not null check (cantidad > 0),
  costo_unitario numeric not null default 0
);

create index if not exists inventario_producto_idx  on public.inventario (producto_id);
create index if not exists movimientos_inv_idx      on public.inventario_movimientos (inventario_id, creado_en desc);
create index if not exists compras_estado_idx       on public.compras (estado);
create index if not exists compra_items_compra_idx  on public.compra_items (compra_id);

-- 2) Seguridad (RLS) --------------------------------------------------------

alter table public.inventario              enable row level security;
alter table public.inventario_movimientos  enable row level security;
alter table public.compras                 enable row level security;
alter table public.compra_items            enable row level security;

drop policy if exists "inventario_autenticados"       on public.inventario;
drop policy if exists "movimientos_autenticados"      on public.inventario_movimientos;
drop policy if exists "compras_autenticados"          on public.compras;
drop policy if exists "compra_items_autenticados"     on public.compra_items;

create policy "inventario_autenticados"      on public.inventario              for all to authenticated using (true) with check (true);
create policy "movimientos_autenticados"     on public.inventario_movimientos  for all to authenticated using (true) with check (true);
create policy "compras_autenticados"         on public.compras                 for all to authenticated using (true) with check (true);
create policy "compra_items_autenticados"    on public.compra_items            for all to authenticated using (true) with check (true);

-- 3) Semilla: cada producto del menú pasa a ser un ítem de inventario en 0.
--    Lo que ya esté en la tabla de inventario NO se toca.
insert into public.inventario (producto_id, nombre, cantidad, unidad, minimo)
select p.id, p.nombre, 0, 'unidad', 5
  from public.productos p
 where not exists (select 1 from public.inventario i where i.producto_id = p.id);

-- 4) Función: registrar una entrada o salida de stock.
--    Nunca deja el inventario en números negativos.
create or replace function public.inventario_registrar(
  p_inventario_id bigint, p_tipo text, p_cantidad numeric, p_motivo text
) returns void
language plpgsql
as $$
begin
  if p_cantidad is null or p_cantidad <= 0 then
    raise exception 'La cantidad debe ser mayor que cero';
  end if;
  if p_tipo not in ('entrada', 'salida') then
    raise exception 'El tipo debe ser "entrada" o "salida"';
  end if;

  update public.inventario
     set cantidad = case when p_tipo = 'entrada'
                         then cantidad + p_cantidad
                         else greatest(cantidad - p_cantidad, 0) end,
         actualizado_en = now()
   where id = p_inventario_id;
  if not found then
    raise exception 'Producto de inventario no encontrado';
  end if;

  insert into public.inventario_movimientos (inventario_id, tipo, cantidad, motivo)
  values (p_inventario_id, p_tipo, p_cantidad, nullif(trim(coalesce(p_motivo, '')), ''));
end;
$$;

-- 5) Función: crear una orden de compra con sus ítems. El total lo calcula el servidor.
create or replace function public.compra_crear(
  p_proveedor text, p_items jsonb
) returns bigint
language plpgsql
as $$
declare
  v_id bigint;
begin
  if p_items is null or jsonb_array_length(p_items) = 0 then
    raise exception 'La compra no tiene productos';
  end if;

  insert into public.compras (proveedor, estado, total)
  values (coalesce(nullif(trim(coalesce(p_proveedor, '')), ''), 'Sin proveedor'), 'enviada', 0)
  returning id into v_id;

  insert into public.compra_items (compra_id, inventario_id, nombre, cantidad, costo_unitario)
  select v_id,
         nullif(i->>'inventario_id', '')::bigint,
         i->>'nombre',
         (i->>'cantidad')::numeric,
         coalesce((i->>'costo')::numeric, 0)
    from jsonb_array_elements(p_items) as i;

  update public.compras
     set total = (select coalesce(sum(cantidad * costo_unitario), 0)
                    from public.compra_items where compra_id = v_id)
   where id = v_id;

  return v_id;
end;
$$;

-- 6) Función: marcar la compra como recibida y sumar el stock.
--    Cada ítem queda registrado como movimiento de entrada.
create or replace function public.compra_recibir(p_compra_id bigint) returns void
language plpgsql
as $$
declare
  r record;
begin
  update public.compras
     set estado = 'recibida', recibido_en = now()
   where id = p_compra_id and estado <> 'recibida';
  if not found then
    raise exception 'Compra no encontrada o ya recibida';
  end if;

  for r in select * from public.compra_items where compra_id = p_compra_id loop
    if r.inventario_id is not null then
      update public.inventario
         set cantidad = cantidad + r.cantidad,
             costo_ultima_compra = r.costo_unitario,
             actualizado_en = now()
       where id = r.inventario_id;

      insert into public.inventario_movimientos (inventario_id, tipo, cantidad, motivo)
      values (r.inventario_id, 'entrada', r.cantidad, 'Compra #' || p_compra_id);
    end if;
  end loop;
end;
$$;

revoke execute on function public.inventario_registrar(bigint, text, numeric, text) from public, anon;
grant  execute on function public.inventario_registrar(bigint, text, numeric, text) to authenticated, service_role;

revoke execute on function public.compra_crear(text, jsonb) from public, anon;
grant  execute on function public.compra_crear(text, jsonb) to authenticated, service_role;

revoke execute on function public.compra_recibir(bigint) from public, anon;
grant  execute on function public.compra_recibir(bigint) to authenticated, service_role;

