-- 1) Datos del negocio que el bot usa para responder -----------------------
create table if not exists public.negocio (
  id           int primary key default 1 check (id = 1),
  nombre       text not null default 'Mi negocio',
  bienvenida   text,
  horario      text,
  direccion    text,
  telefono     text,
  actualizado_en timestamptz not null default now()
);

insert into public.negocio (id, nombre, bienvenida, horario, direccion)
values (1, 'Café & Sabor Criollo',
        '¡Hola! Bienvenido a Café & Sabor Criollo ☕ Puedo mostrarte el menú o tomar tu pedido.',
        'Lunes a sábado, de 7:00 a.m. a 7:00 p.m.',
        '')
on conflict (id) do nothing;

-- 2) Bitácora de la conversación de WhatsApp -------------------------------
create table if not exists public.whatsapp_mensajes (
  id         bigint generated by default as identity primary key,
  wa_id      text not null,                              -- número del cliente
  nombre     text,
  direccion  text not null check (direccion in ('entrante', 'saliente')),
  texto      text,
  pedido_id  bigint references public.pedidos (id) on delete set null,
  creado_en  timestamptz not null default now()
);

create index if not exists wa_mensajes_wa_idx on public.whatsapp_mensajes (wa_id, creado_en desc);

-- 3) Estado de cada conversación (por si luego se agrega un flujo guiado) ---
create table if not exists public.whatsapp_sesiones (
  wa_id        text primary key,
  estado       text not null default 'inicio',
  contexto     jsonb not null default '{}'::jsonb,
  actualizado_en timestamptz not null default now()
);

-- 4) Seguridad (RLS) --------------------------------------------------------
alter table public.negocio             enable row level security;
alter table public.whatsapp_mensajes   enable row level security;
alter table public.whatsapp_sesiones   enable row level security;

drop policy if exists "negocio_autenticados"    on public.negocio;
drop policy if exists "wa_mensajes_autenticados" on public.whatsapp_mensajes;
drop policy if exists "wa_sesiones_autenticados" on public.whatsapp_sesiones;

-- El dueño (sesión iniciada) puede leer y editar; el bot usa la service_role
-- (que no pasa por RLS) para escribir los mensajes que llegan de Meta.
create policy "negocio_autenticados"     on public.negocio           for all to authenticated using (true) with check (true);
create policy "wa_mensajes_autenticados" on public.whatsapp_mensajes for all to authenticated using (true) with check (true);
create policy "wa_sesiones_autenticados" on public.whatsapp_sesiones for all to authenticated using (true) with check (true);

-- 5) Tiempo real: el chat se actualiza solo en la app.
do $$
begin
  alter publication supabase_realtime add table public.whatsapp_mensajes;
exception when duplicate_object then null;
end $$;
